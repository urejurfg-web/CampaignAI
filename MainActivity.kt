@Composable
fun MessengerSelector(vm: AppVM) {
    val selected = vm.current.platforms.toSet()
    Column(verticalArrangement = Arrangement.spacedBy(6.dp)) {
        Text("کانال‌های کمپین 📱", style = MaterialTheme.typography.titleLarge)
        Text("یک یا چند پلتفرم را انتخاب کن. AI برای هر کانال، استراتژی، محتوا، CTA و روش اندازه‌گیری متناسب پیشنهاد می‌دهد.")
        MESSENGER_PLATFORMS.forEach { platform ->
            Row(
                Modifier.fillMaxWidth(),
                horizontalArrangement = Arrangement.SpaceBetween
            ) {
                Text(platform, Modifier.padding(vertical = 8.dp))
                Checkbox(
                    checked = platform in selected,
                    onCheckedChange = { checked ->
                        val next = if (checked) selected + platform else selected - platform
                        vm.current = vm.current.copy(platforms = next.toList())
                    }
                )
            }
        }
        if (selected.isNotEmpty()) {
            Text("انتخاب‌شده: ${selected.joinToString(" • " )}",
                style = MaterialTheme.typography.bodySmall)
        }
    }
}


data class Project(
    val id: Long = System.currentTimeMillis(),
    val businessName: String = "",
    val field: String = "",
    val product: String = "",
    val channel: String = "",
    val price: String = "",
    val directCost: String = "",
    val currentSales: String = "",
    val targetSales: String = "",
    val duration: String = "30",
    val customerTarget: String = "",
    val goal: String = "",
    val notes: String = "",
    val platforms: List<String> = emptyList()
)

data class ChatRequest(val project: Project, val mode: String, val message: String)
data class ChatResponse(val answer: String)

interface Api {
    @POST("chat")
    suspend fun chat(@Body request: ChatRequest): ChatResponse
}

class AppVM : ViewModel() {
    var projects by mutableStateOf(listOf<Project>())
    var current by mutableStateOf(Project())
    var messages by mutableStateOf(listOf<Pair<String,String>>())
    var busy by mutableStateOf(false)
    var lastGenerated by mutableStateOf("")

    private val api = Retrofit.Builder()
        .baseUrl(BuildConfig.API_BASE_URL)
        .addConverterFactory(GsonConverterFactory.create())
        .build().create(Api::class.java)

    fun load(context: Context) {
        val raw = context.getSharedPreferences("campaign_ai", Context.MODE_PRIVATE)
            .getString("projects", "[]") ?: "[]"
        projects = try {
            Gson().fromJson(raw, object : TypeToken<List<Project>>(){}.type)
        } catch (_: Exception) { emptyList() }
    }

    fun save(context: Context) {
        context.getSharedPreferences("campaign_ai", Context.MODE_PRIVATE)
            .edit().putString("projects", Gson().toJson(projects)).apply()
    }

    fun upsert(context: Context) {
        projects = (projects.filterNot { it.id == current.id } + current).takeLast(100)
        save(context)
    }

    fun newProject() { current = Project() }

    fun askInScope(mode: String, text: String) { viewModelScope.launch { ask(mode, text) } }

    suspend fun ask(mode: String, text: String) {
        if (text.isBlank()) return
        messages = messages + ("شما" to text)
        busy = true
        try {
            val r = api.chat(ChatRequest(current, mode, text))
            messages = messages + ("AI" to r.answer)
            lastGenerated = r.answer
        } catch (_: Exception) {
            messages = messages + ("AI" to "اتصال به Backend برقرار نشد. آدرس API و روشن بودن سرور را بررسی کن.")
        } finally { busy = false }
    }
}

@Composable
fun App() {
    val vm: AppVM = viewModel()
    val ctx = androidx.compose.ui.platform.LocalContext.current
    LaunchedEffect(Unit) { vm.load(ctx) }
    var page by remember { mutableStateOf("home") }

    MaterialTheme {
        Scaffold(
            bottomBar = {
                NavigationBar {
                    listOf(
                        "home" to "خانه", "projects" to "پروژه‌ها",
                        "design" to "طراحی", "questions" to "سوال‌ها",
                        "ai" to "AI"
                    ).forEach {
                        NavigationBarItem(
                            selected = page == it.first,
                            onClick = { page = it.first },
                            icon = {},
                            label = { Text(it.second) }
                        )
                    }
                }
            }
        ) { pad ->
            Box(Modifier.padding(pad).fillMaxSize()) {
                when(page) {
                    "home" -> Home(vm) { page = "projects" }
                    "projects" -> Projects(vm, ctx) { vm.current = it; page = "design" }
                    "design" -> Design(vm, ctx)
                    "questions" -> Questions(vm)
                    "ai" -> AIChat(vm)
                }
            }
        }
    }
}

